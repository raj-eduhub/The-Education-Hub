import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {curriculum} from '../../src/data/curriculumCatalog.js';
import {getTopicGuide} from '../../src/topicGuides.js';
import {selectExplanation} from '../../src/data/selectExplanation.js';
import {lessonBeats,beatSpeech} from '../../src/lessonBeats.js';
import {toSpoken} from '../../src/speech.js';
const root='output/curriculum-review/standards-mapping/factor-correction';
const run=JSON.parse(readFileSync('output/curriculum-review/narration-standards-factor.json'));
assert.equal(run.counts.made,2);assert.equal(run.counts.failed,0);assert.equal(run.counts.stale,0);
const newHashes=new Set(run.manifest.filter(b=>b.status==='synthesised').map(b=>b.textHash));
const topic=curriculum.find(t=>t.id==='y7-maths-number'),lesson=selectExplanation(getTopicGuide(topic.subject,topic),1,'Foundation');
const cases=lessonBeats(topic,lesson).map(b=>({topicId:topic.id,text:beatSpeech(b,toSpoken),kind:b.kind,label:lesson.subtopicTitle})).filter(b=>newHashes.has(createHash('sha256').update(b.text).digest('hex')));
assert.equal(cases.length,2);
writeFileSync(`${root}/speech-cases.json`,JSON.stringify(cases,null,2));
const browser=readFileSync('output/playwright/verify-speech-browser.js','utf8').replace('/output/curriculum-review/speech-browser-cases.json',`/${root}/speech-cases.json`);
writeFileSync('output/playwright/verify-factor-speech.js',browser);
console.log('Prepared exact browser checks for both newly synthesised narration beats.');
