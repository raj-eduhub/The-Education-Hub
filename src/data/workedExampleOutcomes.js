// A topic nobody has classified keeps what it has: absence of a decision is not
// a decision to remove.
export function warrantsWorkedExample(topicId, index) {
  const entry = workedExampleOutcomes[topicId];
  if (!entry) return true;
  return entry.examples.includes(Number(index));
}

export function warrantsFormulae(topicId, index) {
  const entry = workedExampleOutcomes[topicId];
  if (!entry) return true;
  return entry.formulae.includes(Number(index));
}

export function classifiedOutcomes(topicId) {
  return workedExampleOutcomes[topicId] ?? null;
}

